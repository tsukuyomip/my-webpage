/**
 * 学マスの画面の当て方。実スクショ 10 枚の実測から決めた値を置く。
 *
 * 座標そのものは持たない。持つのは「どこを探すか」の窓と、
 * 「パネルらしさ」をどう判定するかのしきい値だけ。
 * 端末で寸法が変わっても（1206x2622 と 1179x2556 が混在）比率で効く。
 */
export const gakumas = {
  panel: {
    /**
     * 本文が絶対に来ない左右の余白。ここが「明るくて平坦」ならパネル。
     * 明るさの割合や全幅の連続だけでは、白い服や明るい背景を拾ってしまう
     * （実測: 画像 08 の白いパーカーが全幅で明るく出る）。
     * 余白まで平坦なのは UI の面だけなので、そこを見る。
     */
    marginLeft: [0.06, 0.1] as const,
    marginRight: [0.9, 0.94] as const,
    minLuminance: 170,
    maxGradient: 3.5,

    /**
     * 左右の余白の**色**がどれだけ離れていたら別物とみなすか。
     *
     * パネルは横に連続した 1 枚の面なので、左端と右端の色は近い。
     * 話者チップは左半分しか覆わないので、チップの行は
     * 「左＝チップの色 / 右＝絵」で大きく食い違う。
     *
     * 実測（縦 9 枚）: 本物のパネルの行は色差 60 以下（最大は
     * 半透明パネルの 60）。チップの行は 169 以上。あいだは大きく空いている。
     *
     * 明るさで比べたときは分かれなかった（本物でも中央値 27 の枚があった）。
     * 分かれるのは色。
     */
    maxSideColorDistance: 100,

    /**
     * パネルの上端が入る窓。実測 5 枚で 74.3〜75.7% に収まったが、
     * 行数の多いセリフで伸びる余地を見て広めに取る。
     * この窓のおかげで、明るい服（画像 01 の 51%、画像 08 の 82%）を弾ける。
     */
    topWindow: [0.68, 0.8] as const,
    /** 画像高に対する最低の高さ。実測の本物は 8.5〜12% */
    minHeight: 0.05,
    searchFrom: 0.6,

    /**
     * パネルの左右。検出条件そのものが「左 6〜10% と右 90〜94% がパネルの内側」
     * なので、そこから導ける。明るい行を横に探る方法も試したが、
     * 隣接する明るい絵を巻き込んで 0〜100% まで振れた（実測）ので使わない。
     */
    left: 0.05,
    right: 0.95,
  },

  /** 話者名チップ。パネルの上端をまたいで置かれる。 */
  speakerChip: {
    /**
     * 幅は一定。実測 466/1206 と 456/1179 で、どちらも画像幅の 38.6%
     * （名前の長さ「ことね」と「2943」に依らず同じだった）。
     * 実測値より内側に取る。1px でも外へはみ出すとチップの外の暗い部分が入り、
     * 二値化の基準がそちらに寄って白字が地に溶ける（実測: 画像 03 が真っ白になった）。
     */
    width: 0.38,
    /** 縦が測れなかったときに使う決め打ち（画像高比） */
    above: 0.03,
    below: 0.008,

    /** 測るときの種の位置。チップの左の余白（字が来ない）を狙う */
    seedInset: 0.015,
    seedAbove: 0.01,
    /** 同じ面とみなす色の差 */
    tolerance: 24,
    /** 測れた高さがこの範囲を外れたら、決め打ちに戻す */
    minHeight: 0.015,
    maxHeight: 0.06,
  },

  /**
   * 左上のヘッダチップ。中身は OCR で読んで、書式が合うかで本物か決める。
   * 帯は締める。広く取ると周りの絵がノイズになって、逆に読めなくなる（実測）。
   * 実測でチップは y 8.8〜14.2%、x 2〜45% に入っていた。
   */
  header: {
    band: { x0: 0.0, x1: 0.46, y0: 0.08, y1: 0.15 } as const,
  },

  /**
   * 横向きの字幕。パネルがないので位置は決め打ちになる。
   * 実測 3 枚で字幕が 78〜85%、その下の話者名が 85〜89% に出た。
   */
  landscape: {
    subtitle: { x0: 0.12, x1: 0.88, y0: 0.75, y1: 0.86 } as const,
    speaker: { x0: 0.3, x1: 0.7, y0: 0.855, y1: 0.92 } as const,
  },
} as const

